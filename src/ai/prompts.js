/**
 * 组装最终 system prompt。
 * @param {string} subject 六科键或 auto。
 * @param {object} [ctx] { grade, region, extra }——extra 为用户自定义提示词。
 * @returns {string} 拼装结果。
 */
export function buildSystemPrompt(subject, ctx) {
  const c = ctx || {}
  const parts = [BASE]
  parts.push(SUBJECT_PROMPTS[subject] !== undefined ? SUBJECT_PROMPTS[subject] : AUTO_HINT)
  const scene = []
  if (typeof c.grade === 'string' && c.grade !== '') scene.push('学生当前年级：' + ({ g1: '高一', g2: '高二', g3: '高三' }[c.grade] || c.grade) + '，讲解深度与例题按学段调整；未学内容点明「这是选择性必修/高三内容」。')
  if (typeof c.region === 'string' && c.region !== '') scene.push('考区/教材：' + c.region + '。')
  if (scene.length > 0) parts.push(scene.join('\n'))
  if (typeof c.extra === 'string' && c.extra.trim() !== '') parts.push(c.extra.trim())
  return parts.join('\n\n')
}